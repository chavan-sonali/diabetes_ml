/**
 * Utility to export the complete clinical dataset to standard CSV format
 */
export function exportDatasetToCSV(): string {
  const headers = [
    'PatientID',
    'Pregnancies',
    'Glucose',
    'HbA1c',
    'BloodPressure',
    'SkinThickness',
    'Insulin',
    'BMI',
    'DiabetesPedigreeFunction',
    'Age',
    'Outcome'
  ];

  const rows = SAMPLE_DIABETES_DATASET.map((p) => [
    p.id,
    p.pregnancies,
    p.glucose,
    p.hba1c,
    p.blood_pressure,
    p.skin_thickness,
    p.insulin,
    p.bmi,
    p.dpf,
    p.age,
    p.outcome
  ].join(','));

  return [headers.join(','), ...rows].join('\n');
}
